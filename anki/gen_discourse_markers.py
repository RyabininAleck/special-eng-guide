def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def wrap_front(head: str, task: str, gap: str, direction: str, cat: str) -> str:
    return (
        '<div style="font-size:16px;line-height:1.55;font-family:sans-serif;">'
        f'<div style="font-size:11px;letter-spacing:.12em;color:#8a8a8a;text-transform:uppercase;">{esc(direction)} · {esc(cat)}</div>'
        f'<div style="font-size:40px;font-weight:800;letter-spacing:.04em;margin:18px 0 14px;color:#f2f2f2;line-height:1.15;">{esc(head)}</div>'
        f'<div style="color:#d4a017;font-size:15px;margin-bottom:12px;">{esc(task)}</div>'
        f'<div style="font-style:italic;color:#c8c8c8;font-size:17px;">{esc(gap)}</div>'
        "</div>"
    )


def wrap_back(answer: str, note: str, filled: str, head: str) -> str:
    hi = filled.replace(head.upper(), f"<b>{esc(head.upper())}</b>")
    if "<b>" not in hi:
        hi = esc(filled)
    return (
        '<div style="font-size:16px;line-height:1.55;font-family:sans-serif;">'
        f'<div style="font-size:28px;font-weight:800;color:#f2f2f2;letter-spacing:.03em;">{esc(answer.upper())}</div>'
        f'<div style="color:#9a9a9a;font-size:14px;margin:8px 0 14px;">{esc(note)}</div>'
        f'<div style="font-style:italic;color:#d0d0d0;font-size:17px;">{hi}</div>'
        "</div>"
    )


def main() -> None:
    out = Path(__file__).with_name("discourse_markers.csv")
    rows: list[list[str]] = []
    for en, ru, note, cat, gap, filled, task_en, task_ru in CARDS:
        rows.append(
            [
                wrap_front(en.upper(), task_en, gap, "EN → RU", cat),
                wrap_back(ru, note, filled, en),
                f"en-ru discourse {cat}",
            ]
        )
        rows.append(
            [
                wrap_front(ru.upper(), task_ru, gap, "RU → EN", cat),
                wrap_back(en, note, filled, en),
                f"ru-en discourse {cat}",
            ]
        )

    with out.open("w", encoding="utf-8-sig", newline="") as f:
        f.write("#separator:Semicolon\n")
        f.write("#html:true\n")
        f.write("#tags column:3\n")
        w = csv.writer(f, delimiter=";", quoting=csv.QUOTE_ALL, lineterminator="\n")
        for front, back, tags in rows:
            w.writerow([front, back, tags])

    print(f"{out}  notes={len(rows)}")


if __name__ == "__main__":
    main()
